#!/usr/bin/env python3
"""
    Module aggregate_results: Consolidates the results of all job array tasks
    (execute_array.sh) into a single results_consolidated.csv and a single summary
    metadata — run ONLY after all tasks in the array have finished.
    
    Usage:
        python -u src/aggregate_results.py
"""

import glob
import json
import os
import sys
from pathlib import Path

import pandas as pd

ROOT_DIR = Path(__file__).resolve().parent.parent
if str(ROOT_DIR) not in sys.path:
    sys.path.insert(0, str(ROOT_DIR))

from src import (
    RESULTS_CNN_DIR,
    RESULTS_CRNN_DIR,
    CONSOLIDATED_RESULTS_PATH,
    METADATA_DIR,
    MFCC_LIST,
)


def aggregate_model_reports() -> pd.DataFrame:
    """
        Function aggregate_model_reports: Reads all {n_mfcc}.csv files from MFCC_CNN/ and MFCC_CRNN/ and concatenates them into a single DataFrame.
        Each file is already the consolidated report of the 10 folds for that n_mfcc/model
        (generated by ArtifactStore.save_model_report), so there is no need to
        re-aggregate folds here — just join the files, one per n_mfcc/model.
        
        Params:
            - None.
        
        Returns:
            - A pandas DataFrame containing the concatenated results.
    """
    all_dfs = []
    missing = []

    for results_dir, model_label in [(RESULTS_CNN_DIR, "CNN"), (RESULTS_CRNN_DIR, "CRNN")]:
        for n_mfcc in MFCC_LIST:
            csv_path = os.path.join(results_dir, f"{n_mfcc}.csv")
            if os.path.exists(csv_path):
                all_dfs.append(pd.read_csv(csv_path))
            else:
                missing.append(csv_path)

    if missing:
        print("\n[Warning] The following expected files were not found "
              "(the corresponding array task might not have finished yet "
              "or has failed):")
        for path in missing:
            print(f"  - {path}")

    if not all_dfs:
        raise FileNotFoundError(
            "No results found in MFCC_CNN/ or MFCC_CRNN/. "
            "Check if the array tasks have already run and generated results."
        )

    return pd.concat(all_dfs, ignore_index=True)


def aggregate_metadata() -> dict:
    """
        Function aggregate_metadata: Joins the run_metadata_task{N}.json of each task into a single summary.
        
        Params:
            - None.
        
        Returns:
            - A dictionary containing the summary of the metadata.
    """
    pattern = os.path.join(METADATA_DIR, "run_metadata_task*.json")
    task_files = sorted(glob.glob(pattern))

    summary = {
        "num_tasks_found": len(task_files),
        "tasks": {}
    }

    for path in task_files:
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
        task_id = os.path.basename(path).replace("run_metadata_task", "").replace(".json", "")
        summary["tasks"][task_id] = {
            "pipeline_status": data.get("pipeline_status"),
            "mfcc_list": data.get("parameters", {}).get("mfcc_list"),
            "saved_at": data.get("saved_at"),
        }

    return summary


def main():
    """
        Function main: Entry point of the script. Orchestrates the aggregation of model reports and metadata.
        
        Params:
            - None.
        
        Returns:
            - None.
    """
    print("=" * 65)
    print(" Aggregating results from all job array tasks")
    print("=" * 65)

    final_results = aggregate_model_reports()
    final_results.to_csv(CONSOLIDATED_RESULTS_PATH, index=False)
    print(f"\n[OK] Consolidated results saved at: {CONSOLIDATED_RESULTS_PATH}")
    print(f"     Total rows: {len(final_results)}")

    metadata_summary = aggregate_metadata()
    summary_path = os.path.join(METADATA_DIR, "run_metadata_array_summary.json")
    with open(summary_path, "w", encoding="utf-8") as f:
        json.dump(metadata_summary, f, indent=4, ensure_ascii=False)
    print(f"[OK] Task metadata summary saved at: {summary_path}")

    expected_tasks = 12
    if metadata_summary["num_tasks_found"] < expected_tasks:
        print(f"\n[Warning] Found metadata for only "
              f"{metadata_summary['num_tasks_found']}/{expected_tasks} tasks. "
              f"Confirm that all array tasks finished successfully "
              f"before considering this consolidation complete.")

    print("\nAggregation complete!")


if __name__ == "__main__":
    main()
